  BadgeCheck,
  BarChart3,
  Beef,
  Car,
  ClipboardList,
  Clock,
  Droplets,
  Factory,
  FlaskConical,
  Globe,
  Handshake,
  Landmark,
  Medal,
  Network,
  Package,
  Paintbrush,
  Pill,
  Route,
