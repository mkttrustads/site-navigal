// Os arquivos de conteúdo (content/*.ts) referenciam ícones por nome, para o
// conteúdo continuar sendo dado puro, sem JSX.
const icons: Record<string, LucideIcon> = {
  badgeCheck: BadgeCheck,
  barChart: BarChart3,
  beef: Beef,
  car: Car,
  clipboard: ClipboardList,
  clock: Clock,
  droplets: Droplets,
  factory: Factory,
  flaskConical: FlaskConical,
  globe: Globe,
  handshake: Handshake,
  landmark: Landmark,
  medal: Medal,
  network: Network,
  package: Package,
  paintbrush: Paintbrush,
  pill: Pill,
  route: Route,
  scale: Scale,
  search: Search,
  shield: ShieldCheck,
  shirt: Shirt,
  sofa: Sofa,
  sparkles: Sparkles,
  sprout: Sprout,
  target: Target,
  trophy: Trophy,
  truck: Truck,
  users: Users,
}

export default function Icon({ name, className }: { name: string; className?: string }) {
  const Component = icons[name] ?? Globe
  return <Component aria-hidden="true" strokeWidth={1.6} className={className} />
}
